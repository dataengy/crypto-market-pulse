#!/usr/bin/env python3
"""Generate Lakeflow SQL (pipelines/*.sql) and the AI/BI dashboard from sql/models + sql/dashboard."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from cmp.settings import get, load_config
from cmp.sql_models import model_sql, valid_trade_predicate

HEADER = "-- GENERATED by scripts/build.py from sql/models. Do not edit.\n"
DATASET = "market_history"


def pipeline_files() -> dict[str, str]:
    mv = "CREATE OR REFRESH MATERIALIZED VIEW {name} AS\n{sql};\n"
    return {
        "pipelines/10_silver.sql": HEADER + (
            "CREATE OR REFRESH STREAMING TABLE trades_silver (\n"
            f"  CONSTRAINT valid_trade EXPECT ({valid_trade_predicate()}) ON VIOLATION DROP ROW\n"
            ") AS\n" f"{model_sql('10_silver', 'STREAM(trades_bronze)')};\n"),
        "pipelines/20_dedup.sql": HEADER + mv.format(name="trades_dedup",
                                                     sql=model_sql("20_dedup", "trades_silver")),
        "pipelines/30_1m.sql": HEADER + mv.format(name="trades_1m", sql=model_sql("30_1m", "trades_dedup")),
        "pipelines/40_latest.sql": HEADER + mv.format(name="trades_latest",
                                                      sql=model_sql("40_latest", "trades_dedup")),
    }


def line_widget(key: str, y_field: str, title: str) -> dict:
    return {"widget": {
        "name": key,
        "queries": [{"name": "main_query", "query": {
            "datasetName": DATASET,
            "fields": [{"name": "window_start", "expression": "`window_start`"},
                       {"name": y_field, "expression": f"`{y_field}`"}],
            "disaggregated": True}}],
        "spec": {"version": 3, "widgetType": "line",
                 "encodings": {"x": {"fieldName": "window_start", "scale": {"type": "temporal"}},
                               "y": {"fieldName": y_field, "scale": {"type": "quantitative"}}},
                 "frame": {"title": title, "showTitle": True}}}}


def dashboard(symbol: str) -> dict:
    query = (ROOT / "sql/dashboard/history.sql").read_text(encoding="utf-8")
    if not symbol.isalnum():
        raise ValueError(f"invalid dashboard symbol: {symbol!r}")
    layout = []
    for (key, field, title), pos in zip(
        [("close_price_chart", "close_price", f"{symbol} close · 1m"),
         ("vwap_chart", "vwap", f"{symbol} VWAP · 1m"),
         ("volume_chart", "volume", f"{symbol} volume · 1m")],
        [(0, 0, 6), (6, 0, 6), (0, 6, 12)],
    ):
        item = line_widget(key, field, title)
        item["position"] = {"x": pos[0], "y": pos[1], "width": pos[2], "height": 6}
        layout.append(item)
    return {"datasets": [{"name": DATASET, "displayName": "Market history",
                          "queryLines": [query.replace("{{symbol}}", symbol)]}],
            "pages": [{"name": "market_page", "displayName": "Crypto Market Pulse",
                       "pageType": "PAGE_TYPE_CANVAS", "layout": layout}]}


def generated_files() -> dict[str, str]:
    files = pipeline_files()
    files["dashboards/market_pulse.lvdash.json"] = json.dumps(
        dashboard(get(load_config(ROOT), "dashboard.symbol")), indent=2) + "\n"
    return files


def main() -> None:
    for rel, content in generated_files().items():
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(content, encoding="utf-8")
        print(f"generated {rel}")


if __name__ == "__main__":
    main()
